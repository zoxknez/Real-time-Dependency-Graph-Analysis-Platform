//! SLSA Provenance Implementation
//!
//! Based on SLSA (Supply-chain Levels for Software Artifacts) specification v1.0
//! for build provenance attestations.
//!
//! Reference: https://slsa.dev/spec/v1.0/

use serde::{Deserialize, Serialize};
use std::collections::HashMap;
use chrono::{DateTime, Utc};

// ═══════════════════════════════════════════════════════════════════════════
// SLSA BUILD LEVELS
// ═══════════════════════════════════════════════════════════════════════════

/// SLSA Build Track Levels (v1.0)
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
#[serde(rename_all = "SCREAMING_SNAKE_CASE")]
pub enum SlsaBuildLevel {
    /// Build L0: No guarantees - No SLSA
    L0,
    /// Build L1: Provenance exists - Attestation shows how package was built
    L1,
    /// Build L2: Hosted build platform - Signed provenance, generated by hosted build service
    L2,
    /// Build L3: Hardened builds - Isolated, ephemeral environment; signed, non-falsifiable provenance
    L3,
}

impl SlsaBuildLevel {
    pub fn as_str(&self) -> &'static str {
        match self {
            SlsaBuildLevel::L0 => "L0",
            SlsaBuildLevel::L1 => "L1",
            SlsaBuildLevel::L2 => "L2",
            SlsaBuildLevel::L3 => "L3",
        }
    }

    pub fn description(&self) -> &'static str {
        match self {
            SlsaBuildLevel::L0 => "No SLSA - No provenance guarantees",
            SlsaBuildLevel::L1 => "Provenance exists - Build attestation available",
            SlsaBuildLevel::L2 => "Hosted build platform - Signed provenance from hosted service",
            SlsaBuildLevel::L3 => "Hardened builds - Isolated ephemeral environment, non-falsifiable provenance",
        }
    }

    pub fn requirements(&self) -> Vec<&'static str> {
        match self {
            SlsaBuildLevel::L0 => vec![],
            SlsaBuildLevel::L1 => vec![
                "Provenance exists",
                "Provenance is authentic",
                "Build process documented",
            ],
            SlsaBuildLevel::L2 => vec![
                "All L1 requirements",
                "Hosted build service",
                "Signed provenance",
                "Build service generates provenance",
            ],
            SlsaBuildLevel::L3 => vec![
                "All L2 requirements",
                "Isolated build environment",
                "Ephemeral environment",
                "Non-falsifiable provenance",
                "Hardened builds",
            ],
        }
    }

    /// Check if this level meets or exceeds the required level
    pub fn meets(&self, required: SlsaBuildLevel) -> bool {
        *self >= required
    }
}

// ═══════════════════════════════════════════════════════════════════════════
// SLSA PROVENANCE PREDICATE (in-toto format)
// ═══════════════════════════════════════════════════════════════════════════

/// SLSA Provenance v1.0 predicate type
pub const SLSA_PROVENANCE_V1: &str = "https://slsa.dev/provenance/v1";

/// SLSA Provenance predicate (in-toto Statement wrapper)
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SlsaProvenance {
    /// in-toto Statement type
    #[serde(rename = "_type")]
    pub statement_type: String,
    /// Subject - the artifact(s) this provenance describes
    pub subject: Vec<Subject>,
    /// Predicate type URI
    #[serde(rename = "predicateType")]
    pub predicate_type: String,
    /// The actual provenance data
    pub predicate: ProvenancePredicate,
}

/// Subject of the in-toto statement (the built artifact)
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Subject {
    /// Artifact name
    pub name: String,
    /// Cryptographic digests of the artifact
    pub digest: HashMap<String, String>,
}

/// SLSA Provenance v1.0 predicate
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ProvenancePredicate {
    /// Information about the build
    #[serde(rename = "buildDefinition")]
    pub build_definition: BuildDefinition,
    /// Information about the run
    #[serde(rename = "runDetails")]
    pub run_details: RunDetails,
}

// ═══════════════════════════════════════════════════════════════════════════
// BUILD DEFINITION
// ═══════════════════════════════════════════════════════════════════════════

/// Build definition - what was supposed to happen
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct BuildDefinition {
    /// Build type URI
    #[serde(rename = "buildType")]
    pub build_type: String,
    /// External parameters - user-controlled inputs
    #[serde(rename = "externalParameters")]
    pub external_parameters: ExternalParameters,
    /// Internal parameters - builder-controlled inputs
    #[serde(rename = "internalParameters", skip_serializing_if = "Option::is_none")]
    pub internal_parameters: Option<HashMap<String, serde_json::Value>>,
    /// Resolved dependencies
    #[serde(rename = "resolvedDependencies", skip_serializing_if = "Option::is_none")]
    pub resolved_dependencies: Option<Vec<ResourceDescriptor>>,
}

/// External parameters for the build
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ExternalParameters {
    /// Source repository
    pub repository: String,
    /// Git reference (branch, tag, commit)
    #[serde(rename = "ref", skip_serializing_if = "Option::is_none")]
    pub git_ref: Option<String>,
    /// Build configuration file
    #[serde(skip_serializing_if = "Option::is_none")]
    pub workflow: Option<String>,
    /// Additional inputs
    #[serde(skip_serializing_if = "Option::is_none")]
    pub inputs: Option<HashMap<String, serde_json::Value>>,
}

/// Resource descriptor for dependencies and artifacts
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ResourceDescriptor {
    /// URI of the resource
    pub uri: String,
    /// Cryptographic digests
    #[serde(skip_serializing_if = "Option::is_none")]
    pub digest: Option<HashMap<String, String>>,
    /// Human-readable name
    #[serde(skip_serializing_if = "Option::is_none")]
    pub name: Option<String>,
    /// Download location
    #[serde(rename = "downloadLocation", skip_serializing_if = "Option::is_none")]
    pub download_location: Option<String>,
    /// Media type
    #[serde(rename = "mediaType", skip_serializing_if = "Option::is_none")]
    pub media_type: Option<String>,
    /// Content of the resource (for inline resources)
    #[serde(skip_serializing_if = "Option::is_none")]
    pub content: Option<String>,
    /// Annotations
    #[serde(skip_serializing_if = "Option::is_none")]
    pub annotations: Option<HashMap<String, serde_json::Value>>,
}

// ═══════════════════════════════════════════════════════════════════════════
// RUN DETAILS
// ═══════════════════════════════════════════════════════════════════════════

/// Run details - what actually happened
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RunDetails {
    /// The build service/platform
    pub builder: Builder,
    /// Build metadata
    pub metadata: BuildMetadata,
    /// Byproducts of the build
    #[serde(skip_serializing_if = "Option::is_none")]
    pub byproducts: Option<Vec<ResourceDescriptor>>,
}

/// Builder information
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Builder {
    /// Builder ID (URI)
    pub id: String,
    /// Builder version
    #[serde(skip_serializing_if = "Option::is_none")]
    pub version: Option<HashMap<String, String>>,
    /// Builder dependencies
    #[serde(rename = "builderDependencies", skip_serializing_if = "Option::is_none")]
    pub builder_dependencies: Option<Vec<ResourceDescriptor>>,
}

/// Build metadata
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct BuildMetadata {
    /// Build invocation ID
    #[serde(rename = "invocationId", skip_serializing_if = "Option::is_none")]
    pub invocation_id: Option<String>,
    /// Build start time
    #[serde(rename = "startedOn", skip_serializing_if = "Option::is_none")]
    pub started_on: Option<DateTime<Utc>>,
    /// Build finish time
    #[serde(rename = "finishedOn", skip_serializing_if = "Option::is_none")]
    pub finished_on: Option<DateTime<Utc>>,
}

