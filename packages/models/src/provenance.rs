/// Builder for constructing SLSA Provenance
pub struct ProvenanceBuilder {
    subjects: Vec<Subject>,
    build_type: String,
    external_params: ExternalParameters,
    internal_params: Option<HashMap<String, serde_json::Value>>,
    dependencies: Vec<ResourceDescriptor>,
    builder_id: String,
    builder_version: Option<String>,
    started_on: Option<DateTime<Utc>>,
    finished_on: Option<DateTime<Utc>>,
    invocation_id: Option<String>,
}

impl ProvenanceBuilder {
    pub fn new(builder_id: impl Into<String>, repository: impl Into<String>) -> Self {
        Self {
            subjects: Vec::new(),
            build_type: "https://slsa.dev/container-based-build/v0.1".to_string(),
            external_params: ExternalParameters {
                repository: repository.into(),
                git_ref: None,
                workflow: None,
                inputs: None,
            },
            internal_params: None,
            dependencies: Vec::new(),
            builder_id: builder_id.into(),
            builder_version: None,
            started_on: None,
            finished_on: None,
            invocation_id: None,
        }
    }

    /// Add a subject (built artifact)
    pub fn add_subject(mut self, name: impl Into<String>, sha256: impl Into<String>) -> Self {
        let mut digest = HashMap::new();
        digest.insert("sha256".to_string(), sha256.into());
        self.subjects.push(Subject {
            name: name.into(),
            digest,
        });
        self
    }

    /// Set the build type
    pub fn build_type(mut self, build_type: impl Into<String>) -> Self {
        self.build_type = build_type.into();
        self
    }

    /// Set the git reference
    pub fn git_ref(mut self, git_ref: impl Into<String>) -> Self {
        self.external_params.git_ref = Some(git_ref.into());
        self
    }

    /// Set the workflow
    pub fn workflow(mut self, workflow: impl Into<String>) -> Self {
        self.external_params.workflow = Some(workflow.into());
        self
    }

    /// Add a dependency
    pub fn add_dependency(mut self, uri: impl Into<String>, sha256: Option<String>) -> Self {
        let digest = sha256.map(|h| {
            let mut d = HashMap::new();
            d.insert("sha256".to_string(), h);
            d
        });
        self.dependencies.push(ResourceDescriptor {
            uri: uri.into(),
            digest,
            name: None,
            download_location: None,
            media_type: None,
            content: None,
            annotations: None,
        });
        self
    }

    /// Set builder version
    pub fn builder_version(mut self, version: impl Into<String>) -> Self {
        self.builder_version = Some(version.into());
        self
    }

    /// Set build timestamps
    pub fn timestamps(mut self, started: DateTime<Utc>, finished: DateTime<Utc>) -> Self {
        self.started_on = Some(started);
        self.finished_on = Some(finished);
        self
    }

    /// Set invocation ID
    pub fn invocation_id(mut self, id: impl Into<String>) -> Self {
        self.invocation_id = Some(id.into());
        self
    }

    /// Build the provenance
    pub fn build(self) -> SlsaProvenance {
        let builder_version = self.builder_version.map(|v| {
            let mut m = HashMap::new();
            m.insert("version".to_string(), v);
            m
        });

        SlsaProvenance {
            statement_type: "https://in-toto.io/Statement/v1".to_string(),
            subject: self.subjects,
            predicate_type: SLSA_PROVENANCE_V1.to_string(),
            predicate: ProvenancePredicate {
                build_definition: BuildDefinition {
                    build_type: self.build_type,
                    external_parameters: self.external_params,
                    internal_parameters: self.internal_params,
                    resolved_dependencies: if self.dependencies.is_empty() {
                        None
                    } else {
                        Some(self.dependencies)
                    },
                },
                run_details: RunDetails {
                    builder: Builder {
                        id: self.builder_id,
                        version: builder_version,
                        builder_dependencies: None,
                    },
                    metadata: BuildMetadata {
                        invocation_id: self.invocation_id,
                        started_on: self.started_on,
                        finished_on: self.finished_on,
                    },
                    byproducts: None,
                },
            },
        }
    }
}

