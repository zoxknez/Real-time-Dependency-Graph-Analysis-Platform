/// SLSA assessment result for a package
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SlsaAssessment {
    /// Package identifier
    pub package_id: String,
    /// Achieved SLSA level
    pub level: SlsaBuildLevel,
    /// Whether provenance exists
    pub has_provenance: bool,
    /// Whether provenance is signed
    pub provenance_signed: bool,
    /// Builder information
    pub builder: Option<String>,
    /// Source repository
    pub source_repo: Option<String>,
    /// Assessment timestamp
    pub assessed_at: DateTime<Utc>,
    /// Improvement recommendations
    pub recommendations: Vec<String>,
}

impl SlsaAssessment {
    /// Generate recommendations for improving SLSA level
    pub fn generate_recommendations(level: SlsaBuildLevel) -> Vec<String> {
        match level {
            SlsaBuildLevel::L0 => vec![
                "Add build provenance generation to your CI/CD pipeline".to_string(),
                "Document your build process".to_string(),
                "Consider using GitHub Actions or similar for reproducible builds".to_string(),
            ],
            SlsaBuildLevel::L1 => vec![
                "Move to a hosted build service (GitHub Actions, GitLab CI, etc.)".to_string(),
                "Enable provenance signing".to_string(),
                "Ensure build service generates provenance automatically".to_string(),
            ],
            SlsaBuildLevel::L2 => vec![
                "Enable isolated build environments".to_string(),
                "Use ephemeral build runners".to_string(),
                "Implement hermetic builds".to_string(),
                "Enable non-falsifiable provenance".to_string(),
            ],
            SlsaBuildLevel::L3 => vec![
                "Maintain current security posture".to_string(),
                "Consider additional supply chain security measures".to_string(),
            ],
        }
    }
}

