/// Result of provenance verification
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ProvenanceVerification {
    /// Whether verification passed
    pub valid: bool,
    /// Achieved SLSA level
    pub slsa_level: SlsaBuildLevel,
    /// Verification details
    pub details: Vec<VerificationCheck>,
    /// Errors encountered
    pub errors: Vec<String>,
    /// Warnings
    pub warnings: Vec<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct VerificationCheck {
    pub name: String,
    pub passed: bool,
    pub message: Option<String>,
}

/// Provenance verifier
pub struct ProvenanceVerifier {
    /// Trusted builder IDs
    trusted_builders: Vec<String>,
    /// Required SLSA level
    required_level: SlsaBuildLevel,
}

impl ProvenanceVerifier {
    pub fn new(required_level: SlsaBuildLevel) -> Self {
        Self {
            trusted_builders: Vec::new(),
            required_level,
        }
    }

    /// Add a trusted builder
    pub fn trust_builder(mut self, builder_id: impl Into<String>) -> Self {
        self.trusted_builders.push(builder_id.into());
        self
    }

    /// Verify provenance
    pub fn verify(&self, provenance: &SlsaProvenance) -> ProvenanceVerification {
        let mut checks = Vec::new();
        let mut errors = Vec::new();
        let mut warnings = Vec::new();

        // Check 1: Valid statement type
        let valid_statement = provenance.statement_type == "https://in-toto.io/Statement/v1";
        checks.push(VerificationCheck {
            name: "Valid in-toto statement".to_string(),
            passed: valid_statement,
            message: if valid_statement { None } else { Some("Invalid statement type".to_string()) },
        });

        // Check 2: Valid predicate type
        let valid_predicate = provenance.predicate_type == SLSA_PROVENANCE_V1;
        checks.push(VerificationCheck {
            name: "Valid SLSA predicate".to_string(),
            passed: valid_predicate,
            message: if valid_predicate { None } else { Some("Invalid predicate type".to_string()) },
        });

        // Check 3: Has subjects
        let has_subjects = !provenance.subject.is_empty();
        checks.push(VerificationCheck {
            name: "Has subjects".to_string(),
            passed: has_subjects,
            message: if has_subjects { None } else { Some("No subjects defined".to_string()) },
        });

        // Check 4: Subjects have digests
        let subjects_have_digests = provenance.subject.iter().all(|s| !s.digest.is_empty());
        checks.push(VerificationCheck {
            name: "Subjects have digests".to_string(),
            passed: subjects_have_digests,
            message: if subjects_have_digests { None } else { Some("Some subjects missing digests".to_string()) },
        });

        // Check 5: Builder is trusted
        let builder_trusted = self.trusted_builders.is_empty() 
            || self.trusted_builders.contains(&provenance.predicate.run_details.builder.id);
        checks.push(VerificationCheck {
            name: "Builder is trusted".to_string(),
            passed: builder_trusted,
            message: if builder_trusted { None } else { 
                Some(format!("Builder {} not in trusted list", provenance.predicate.run_details.builder.id))
            },
        });

        // Check 6: Has build metadata
        let has_metadata = provenance.predicate.run_details.metadata.started_on.is_some();
        checks.push(VerificationCheck {
            name: "Has build timestamps".to_string(),
            passed: has_metadata,
            message: if has_metadata { None } else { Some("Missing build timestamps".to_string()) },
        });

        // Determine SLSA level
        let all_passed = checks.iter().all(|c| c.passed);
        let slsa_level = if !all_passed {
            SlsaBuildLevel::L0
        } else if builder_trusted && has_metadata {
            SlsaBuildLevel::L2
        } else {
            SlsaBuildLevel::L1
        };

        if !slsa_level.meets(self.required_level) {
            errors.push(format!(
                "Achieved {} but required {}",
                slsa_level.as_str(),
                self.required_level.as_str()
            ));
        }

        if !has_metadata {
            warnings.push("Missing build timestamps - cannot verify build freshness".to_string());
        }

        ProvenanceVerification {
            valid: all_passed && slsa_level.meets(self.required_level),
            slsa_level,
            details: checks,
            errors,
            warnings,
        }
    }
}

